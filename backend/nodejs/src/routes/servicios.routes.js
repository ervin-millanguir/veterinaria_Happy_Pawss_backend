const express = require('express');
const router = express.Router();
const controller = require('../controllers/servicios.controller');
const { verificarToken, permitirRoles } = require('../middleware/auth.middleware');
router.get('/', controller.listar);
router.get('/:id', controller.buscarPorId);
router.post('/', verificarToken, permitirRoles('administrador'), controller.crear);
router.put('/:id', verificarToken, permitirRoles('administrador'), controller.actualizar);
router.delete('/:id', verificarToken, permitirRoles('administrador'), controller.eliminar);
module.exports = router;
